(function () {
  // Ціни по напрямах (підстав свої)
  var PRICES = {
    muay:     { name: 'Тайський бокс',            single: 250, eight: 1400, unlimited: 1900 },
    personal: { name: 'Індивідуальні тренування', single: 500, eight: 3600, unlimited: null },
    kick:     { name: 'Кікбоксинг',               single: 200, eight: 1200, unlimited: 1800 },
    kids:     { name: 'Karate Kids',              single: 150, eight: 1000, unlimited: null },
    fitness:  { name: 'Fitness',                  single: 150, eight: 1000, unlimited: 1500 }
  };
  var fmt = function (n) { return String(n).replace(/\B(?=(\d{3})+(?!\d))/g, ' '); };

  // 0. Логотип: додається в .brand, навіть якщо в HTML його немає
  var brand = document.querySelector('.brand');
  var logo = brand.querySelector('.logo');
  if (!logo) {
    var old = brand.querySelector('svg, img');
    if (old) old.remove();
    logo = document.createElement('i');
    logo.className = 'logo';
    logo.style.cssText = 'display:block;line-height:0';
    brand.insertBefore(logo, brand.firstChild);
  }
  logo.innerHTML = LOGO;
  brand.addEventListener('mouseenter', function () { logo.firstChild.style.transform = 'scale(1.08)'; });
  brand.addEventListener('mouseleave', function () { logo.firstChild.style.transform = ''; });
  logo.firstChild.style.transition = 'transform .4s';

  // 1. Активний пункт меню
  var page = location.pathname.split('/').pop() || 'index.html';
  document.querySelectorAll('.nav nav a').forEach(function (a) {
    if (a.getAttribute('href') === page) a.classList.add('active');
  });

  // 2. Бургер-меню (телефон)
  var burger = document.querySelector('.burger');
  var menu = document.getElementById('menu');
  burger.addEventListener('click', function () {
    var open = menu.classList.toggle('open');
    burger.setAttribute('aria-expanded', open);
  });
  menu.querySelectorAll('a').forEach(function (a) {
    a.addEventListener('click', function () {
      menu.classList.remove('open');
      burger.setAttribute('aria-expanded', 'false');
    });
  });

  // 3. Назва залу: перехід на головну
  brand.addEventListener('click', function (e) {
    if (page === 'index.html') {
      e.preventDefault();
      window.scrollTo({ top: 0, behavior: 'smooth' });
    }
  });

  // 4. Анімація при наведенні (ПК: мишка, телефон: дотик)
  document.querySelectorAll('.nav nav a, .glow').forEach(function (el) {
    var on = function (e) {
      el.classList.add('hovered');
      var p = e.touches ? e.touches[0] : e;
      var r = el.getBoundingClientRect();
      el.style.setProperty('--x', (p.clientX - r.left) + 'px');
      el.style.setProperty('--y', (p.clientY - r.top) + 'px');
    };
    var off = function () { el.classList.remove('hovered'); };
    el.addEventListener('mouseenter', on);
    el.addEventListener('mousemove', on);
    el.addEventListener('mouseleave', off);
    el.addEventListener('touchstart', on, { passive: true });
    el.addEventListener('touchend', function () { setTimeout(off, 250); });
    el.addEventListener('focus', on);
    el.addEventListener('blur', off);
  });

  // 5. Розклад: позначити сьогоднішній день
  var today = document.querySelector('.day[data-day="' + new Date().getDay() + '"]');
  if (today && !today.classList.contains('off')) today.classList.add('today');

  // 6. Ціни: показати ціни обраного напряму
  var plans = document.getElementById('plans');
  if (plans) {
    var picker = document.getElementById('picker');
    var lead = document.getElementById('lead');
    var note = document.getElementById('note');
    var keys = ['single', 'eight', 'unlimited'];

    function render(sport, scroll) {
      if (sport !== 'all' && !PRICES[sport]) sport = 'all';

      picker.querySelectorAll('button').forEach(function (b) {
        b.classList.toggle('on', b.dataset.sport === sport);
      });

      keys.forEach(function (k) {
        var card = plans.querySelector('[data-plan="' + k + '"]');
        var value, prefix = '';
        if (sport === 'all') {
          var all = Object.keys(PRICES).map(function (s) { return PRICES[s][k]; })
                          .filter(function (v) { return v !== null; });
          value = Math.min.apply(null, all);
          prefix = 'від ';
        } else {
          value = PRICES[sport][k];
        }
        if (value === null) { card.hidden = true; return; }
        card.hidden = false;
        card.querySelector('.num').textContent = prefix + fmt(value);
        card.classList.remove('flash');
        void card.offsetWidth;
        card.classList.add('flash');
      });

      if (sport === 'all') {
        lead.textContent = 'Обери напрям, і ми покажемо ціни саме для нього.';
        note.textContent = 'Індивідуальні тренування — вартість за домовленістю з тренером.';
      } else {
        lead.textContent = 'Ціни для напряму «' + PRICES[sport].name + '».';
        note.textContent = PRICES[sport].unlimited === null
          ? 'Для цього напряму безлімітний абонемент недоступний.'
          : '';
      }

      var url = sport === 'all' ? 'prices.html' : 'prices.html?sport=' + sport;
      try { history.replaceState(null, '', url); } catch (e) {}
      if (scroll) plans.scrollIntoView({ behavior: 'smooth', block: 'center' });
    }

    picker.addEventListener('click', function (e) {
      var b = e.target.closest('button');
      if (b) render(b.dataset.sport, false);
    });

    var chosen = new URLSearchParams(location.search).get('sport') || 'all';
    render(chosen, chosen !== 'all');
  }
})();
